    for (let i = 0; i < ps.count; i++) { const y = ps.getY(i) / 20, cc = y > 0 ? mid.clone().lerp(top, y) : mid.clone().lerp(bot, -y); col.push(cc.r, cc.g, cc.b); }
    sky.setAttribute('color', new T.Float32BufferAttribute(col, 3));
