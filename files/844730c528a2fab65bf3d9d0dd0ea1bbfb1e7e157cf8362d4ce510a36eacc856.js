  function tour(g) {
    const card = g.querySelector('.guide-card');
    if (!card || typeof tr !== 'function') return;
    if (!card.classList.contains('ps-tour')) {
      const h = card.querySelector('#guide-title'), ok = card.querySelector('#guide-ok');
      h.removeAttribute('data-i18n'); h.tabIndex = -1;
      ok.dataset.i18n = 'tour_go'; ok.textContent = tr('tour_go'); // ui.js's language switch relabels it
      card.classList.add('ps-tour');
      card.innerHTML = `<div class="ps-tour-top"><div class="lang" role="group" aria-label="${esc(tr('language'))}"><button data-tl="en" lang="en">EN</button><button data-tl="el" lang="el">ΕΛ</button></div>
        <button class="btn ghost" data-t="skip"></button></div>
        <div class="ps-tour-art" aria-hidden="true"></div>
        <div class="ps-tour-txt"><p class="ps-tour-n"></p><h2></h2><p class="ps-tour-x" id="ps-tour-x"></p><p class="ps-tour-note"></p></div>
        <div class="ps-tour-foot"><div class="ps-tour-dots">${Array.from({ length: TOUR_N }, (_, i) => `<button data-n="${i}"></button>`).join('')}</div><button class="btn" data-t="back"></button><button class="btn primary" data-t="next"></button></div>`;
      card.querySelector('h2').replaceWith(h); card.querySelector('.ps-tour-foot').append(ok); // the same nodes: ui.js keeps its listener and aria-labelledby its target
      g.setAttribute('aria-describedby', 'ps-tour-x');
      card.addEventListener('click', e => {
        const b = e.target.closest('button'); if (!b) return;
        if (b.dataset.tl) { document.querySelector(`#lang [data-lang="${b.dataset.tl}"]`)?.click(); tourStep(card, tourAt); }
        else if (b.dataset.t === 'skip') ok.click();
        else if (b.dataset.t) tourStep(card, tourAt + (b.dataset.t === 'next' ? 1 : -1));
        else if (b.dataset.n) tourStep(card, +b.dataset.n);
      });
      card.addEventListener('keydown', e => {
        if ((e.key === 'ArrowRight' || e.key === 'ArrowLeft') && !e.altKey && !e.target.closest('.lang')) { e.preventDefault(); tourStep(card, tourAt + (e.key === 'ArrowRight' ? 1 : -1)); }
        else if (e.key === 'Tab') { // keep the keyboard inside the dialog
          const f = [...card.querySelectorAll('button')].filter(b => b.offsetParent), a = f[0], z = f.at(-1);
          if (e.shiftKey ? document.activeElement === a : document.activeElement === z) { e.preventDefault(); (e.shiftKey ? z : a).focus(); }
        }
      });
      let x0 = null; // a sideways swipe turns the page
      card.addEventListener('pointerdown', e => { x0 = e.isPrimary && !e.target.closest('button') ? [e.clientX, e.clientY] : null; });
      card.addEventListener('pointerup', e => { if (!x0) return; const dx = e.clientX - x0[0], dy = e.clientY - x0[1]; x0 = null; if (Math.abs(dx) > 48 && Math.abs(dx) > 1.5 * Math.abs(dy)) tourStep(card, tourAt + (dx < 0 ? 1 : -1)); });
      new MutationObserver(() => { if (g.hidden && tourFrom?.isConnected) { tourFrom.focus({ preventScroll: true }); tourFrom = null; } }).observe(g, { attributes: true, attributeFilter: ['hidden'] });
      g.classList.add('is-tour');
    }
    if (!g.contains(document.activeElement)) tourFrom = document.activeElement;
    tourStep(card, 0, true);
  }
  function tourStep(card, n, first) {
    n = clamp(n, 0, TOUR_N - 1);
    const moved = n !== tourAt || first, q = s => card.querySelector(s), k = n + 1, last = n === TOUR_N - 1;
    tourAt = n;
    q('.ps-tour-art').innerHTML = ART[n]();
    q('.ps-tour-n').textContent = tr('tour_step', k, TOUR_N);
    q('#guide-title').textContent = tr('tv_t' + k);
    q('.ps-tour-x').textContent = tr('tv_x' + k);
    q('.ps-tour-note').textContent = k === 1 ? tr('tour_honest') : '';
    card.querySelectorAll('[data-n]').forEach((b, i) => { b.setAttribute('aria-label', tr('tour_step', i + 1, TOUR_N)); if (i === n) b.setAttribute('aria-current', 'step'); else b.removeAttribute('aria-current'); });
    for (const b of card.querySelectorAll('[data-tl]')) b.setAttribute('aria-pressed', b.dataset.tl === state.lang);
    const [skip, back, next, ok] = ['[data-t=skip]', '[data-t=back]', '[data-t=next]', '#guide-ok'].map(q);
    skip.textContent = tr('tour_skip'); back.textContent = tr('tour_back'); next.textContent = tr('tour_next');
    skip.hidden = last; back.hidden = !n; next.hidden = last; ok.hidden = !last;
    if (moved) { card.classList.remove('is-in'); void card.offsetWidth; card.classList.add('is-in'); } // replay the entrance (none with reduced motion: app.css)
    if (first || !card.contains(document.activeElement) || document.activeElement.hidden) (last ? ok : next).focus({ preventScroll: true });
  }

