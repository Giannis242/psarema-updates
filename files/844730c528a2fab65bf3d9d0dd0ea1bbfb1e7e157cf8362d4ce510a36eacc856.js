  const toneAt = (seg, i) => { let n = seg[0][1]; for (const s of seg) if (i >= s[0]) n = s[1]; return n; };
  // poses are stored as integer thousandths; decode once per knot
  const posesOf = k => k._poses || (k._poses = k.poses.map(pp => pp.map(P => Float32Array.from(P, v => v / 1000))));
  // control points of a line at a key, with the key's twist applied (dropper)
  function keyPoints(k, key, l) {
    const P = posesOf(k)[key.p][l];
    if (!key.tw || !k.twist) return P;
    const w = k.twist.w[l], o = new Float32Array(P.length);
    for (let i = 0; i < P.length; i += 3) { const a = key.tw * w[i / 3], c = Math.cos(a), s = Math.sin(a); o[i] = P[i]; o[i + 1] = P[i + 1] * c - P[i + 2] * s; o[i + 2] = P[i + 1] * s + P[i + 2] * c; }
    return o;
  }
  const chord = (P, a, b) => { // length along control points between fractional indices a < b
    if (b < a) [a, b] = [b, a];
    let L = 0;
    for (let i = Math.floor(a); i < Math.ceil(b) && i < P.length / 3 - 1; i++) {
      const f0 = Math.max(0, a - i), f1 = Math.min(1, b - i), d = Math.hypot(P[3 * i + 3] - P[3 * i], P[3 * i + 4] - P[3 * i + 1], P[3 * i + 5] - P[3 * i + 2]);
      L += d * Math.max(0, f1 - f0);
    }
    return L;
  };
  const basis = n => { const a = Math.abs(n[1]) < 0.9 ? [0, 1, 0] : [1, 0, 0]; let u = [n[1] * a[2] - n[2] * a[1], n[2] * a[0] - n[0] * a[2], n[0] * a[1] - n[1] * a[0]]; const l = Math.hypot(...u); u = u.map(v => v / l); return [u, [n[1] * u[2] - n[2] * u[1], n[2] * u[0] - n[0] * u[2], n[0] * u[1] - n[1] * u[0]]]; };

  // ---------- flat picture (list thumbnails, and the fallback without WebGL) ----------
  // Orthographic projection, segments painted far to near so crossings read correctly.
  function flatKnot(k, w) {
    if (!k.poses) return '';
    const ry = -0.42, rx = 0.32, cy = Math.cos(ry), sy = Math.sin(ry), cx = Math.cos(rx), sx = Math.sin(rx);
    const P = (x, y, z) => { const x1 = x * cy + z * sy, z1 = -x * sy + z * cy; return [x1, -(y * cx - z1 * sx), y * sx + z1 * cx]; };
    const f = k.focus, c = P(f[0], f[1], f[2]), R = f[3] * 1.05, segs = [];
    const push = (pts, r, cls) => { for (let i = 0; i < pts.length - 1; i++) { const a = pts[i], b = pts[i + 1]; segs.push({ a, b, z: (a[2] + b[2]) / 2, r, cls: typeof cls === 'function' ? cls(i) : cls }); } };
    const pts3 = (F, a = 0, b = F.length / 3 - 1) => { const o = []; for (let i = a; i <= b; i++) o.push(P(F[3 * i], F[3 * i + 1], F[3 * i + 2])); return o; };
    for (const p of k.parts || []) {
      if (p.k === 'torus') { const [u, v] = basis(p.n), ring = []; for (let i = 0; i <= 32; i++) { const a = i / 32 * Math.PI * 2, q = [0, 1, 2].map(j => p.c[j] + p.R * (u[j] * Math.cos(a) + v[j] * Math.sin(a))); ring.push(P(...q)); } push(ring, p.r, 'ps-tone-metal'); }
      if (p.k === 'tube') push(pts3(p.p), Array.isArray(p.r) ? p.r[0] : p.r, 'ps-tone-metal');
      if (p.k === 'body') push([P(...p.a), P(...p.b)], Math.max(...p.prof.map(q => q[1])) * 0.9, p.m === 'lure' ? 'ps-tone-lure' : 'ps-tone-metal');
    }
    const key = k.keys[k.flat == null ? k.keys.length - 1 : k.flat];
    k.tubes.forEach((ln, l) => {
      const [a, b] = key.s[l], i0 = Math.ceil(a), i1 = Math.floor(b);
      if (i1 > i0) push(pts3(keyPoints(k, key, l), i0, i1), ln.r, i => 'ps-tone-' + toneAt(ln.seg, i0 + i));
    });
    segs.sort((p, q) => q.z - p.z);
    const n = v => (Math.round(v * 1000) / 1000);
    const body = segs.map(s => {
      const xy = `x1="${n(s.a[0])}" y1="${n(s.a[1])}" x2="${n(s.b[0])}" y2="${n(s.b[1])}"`;
      return `<line ${xy} class="ps-flat-edge" stroke-width="${n(s.r * w + R * 0.03)}"/><line ${xy} class="${s.cls}" stroke-width="${n(s.r * w)}"/>`;
    }).join('');
    return `<svg class="ps-flat" viewBox="${n(c[0] - R)} ${n(c[1] - R)} ${n(2 * R)} ${n(2 * R)}" aria-hidden="true">${body}</svg>`;
  }
  const flatOf = (k, w) => (k._flat ||= {})[w] ||= flatKnot(k, w); // the same picture in either language: built once per knot and size

