    const f = k.focus, center = new T.Vector3(f[0], f[1], f[2]);
    const sun = new T.DirectionalLight(0xffffff, 1.25);
    sun.position.copy(center).add(new T.Vector3(1.5, 9, 3)); sun.target.position.copy(center);
    sun.castShadow = true;
    Object.assign(sun.shadow.camera, { left: -f[3] * 1.9, right: f[3] * 1.9, top: f[3] * 1.9, bottom: -f[3] * 1.9, near: 2, far: 22 });
    sun.shadow.camera.updateProjectionMatrix();
    sun.shadow.mapSize.set(coarse ? 512 : 1024, coarse ? 512 : 1024); sun.shadow.bias = -0.0008; sun.shadow.normalBias = 0.02;
    scene.add(sun, sun.target, new T.HemisphereLight(0xffffff, 0x303030, 0.35));

    // floor that only shows the shadow, fading out towards its edge
    const floorR = f[3] * 2.4, floorGeo = new T.PlaneGeometry(floorR * 2, floorR * 2);
